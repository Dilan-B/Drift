#!/usr/bin/env node
/**
 * tools/i18n/build.js — turn translations into everything that ships.
 *
 *   node tools/i18n/scan.js     # 1. collect keys   → i18n/keys.json
 *   node tools/i18n/build.js    # 2. emit catalogs  (this file)
 *
 * Translations are authored in i18n/src/<code>.tsv, one "<n>\t<text>" line
 * per key, where <n> is the key's line in i18n/src/_source.tsv (regenerated
 * here from keys.json; newlines inside a string are written as \n). Numbering
 * instead of repeating the English keeps the files half the size and makes a
 * missing line obvious.
 *
 * Every translation is checked before it's used: its {{placeholders}} must be
 * exactly the English key's, or it's dropped (falls back to English) and
 * reported — a typo'd placeholder would otherwise print "{{nmae}}" to users.
 *
 * Outputs:
 *   i18n/locales/<code>.json                         app catalogs
 *   supabase/functions/_shared/push_i18n.ts          server-sent push copy
 *   ios/<target>/*.swift  (between L10N markers)     shield / monitor / widget
 *   ios/Drift/<code>.lproj/InfoPlist.strings         permission prompts
 *
 * `--check` validates without writing.
 */
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, "../..");
const I18N = path.join(ROOT, "i18n");
const CHECK = process.argv.includes("--check");

const read = (p) => JSON.parse(fs.readFileSync(p, "utf8"));
const keys = Object.keys(read(path.join(I18N, "keys.json")));
const langsSrc = fs.readFileSync(path.join(I18N, "languages.js"), "utf8");
const LANGS = [...langsSrc.matchAll(/code: "([^"]+)"/g)].map((m) => m[1]).filter((c) => c !== "en");

const esc = (s) => s.replace(/\\/g, "\\\\").replace(/\n/g, "\\n").replace(/\t/g, "\\t");
const unesc = (s) => s.replace(/\\(n|t|\\)/g, (_, c) => (c === "n" ? "\n" : c === "t" ? "\t" : "\\"));
const placeholders = (s) => [...s.matchAll(/\{\{(\w+)\}\}/g)].map((m) => m[1]).sort().join(",");

// _source.tsv is append-stable: existing keys keep their numbers so a key
// added later never shifts every translation by one.
const srcPath = path.join(I18N, "src", "_source.tsv");
fs.mkdirSync(path.dirname(srcPath), { recursive: true });
const numbered = new Map(); // key -> n
if (fs.existsSync(srcPath)) {
  for (const line of fs.readFileSync(srcPath, "utf8").split("\n")) {
    const i = line.indexOf("\t");
    if (i > 0) numbered.set(unesc(line.slice(i + 1)), Number(line.slice(0, i)));
  }
}
let next = Math.max(0, ...numbered.values()) + 1;
for (const k of keys) if (!numbered.has(k)) numbered.set(k, next++);
const live = new Set(keys);
const byNum = new Map([...numbered].filter(([k]) => live.has(k)).map(([k, n]) => [n, k]));
if (!CHECK) {
  fs.writeFileSync(srcPath, [...byNum].sort((a, b) => a[0] - b[0]).map(([n, k]) => `${n}\t${esc(k)}`).join("\n") + "\n");
}

const catalogs = {};
let problems = 0;
for (const code of LANGS) {
  const p = path.join(I18N, "src", `${code}.tsv`);
  const dict = {};
  if (fs.existsSync(p)) {
    for (const [ln, line] of fs.readFileSync(p, "utf8").split("\n").entries()) {
      if (!line.trim()) continue;
      const i = line.indexOf("\t");
      const n = Number(line.slice(0, i));
      const key = byNum.get(n);
      if (i < 0 || !key) continue; // retired key or junk line
      const val = unesc(line.slice(i + 1)).trim();
      if (!val) continue;
      if (placeholders(val) !== placeholders(key)) {
        problems++;
        console.warn(`${code}.tsv:${ln + 1} placeholder mismatch for #${n} — dropped`);
        continue;
      }
      dict[key] = val;
    }
  }
  catalogs[code] = dict;
}

const report = LANGS.map((c) => `${c}:${Math.round((Object.keys(catalogs[c]).length / keys.length) * 100)}%`);
console.log(`${keys.length} keys. Coverage ${report.join(" ")}`);
if (CHECK) process.exit(problems ? 1 : 0);

// 1. App catalogs
for (const code of LANGS) {
  const appOnly = {};
  for (const [k, v] of Object.entries(catalogs[code])) appOnly[k] = v;
  fs.writeFileSync(path.join(I18N, "locales", `${code}.json`), JSON.stringify(appOnly) + "\n");
}

// 2. Server push copy
const serverKeys = Object.keys(read(path.join(I18N, "server-keys.json")));
const push = {};
for (const code of LANGS) {
  const m = {};
  for (const k of serverKeys) if (catalogs[code][k]) m[k] = catalogs[code][k];
  if (Object.keys(m).length) push[code] = m;
}
fs.writeFileSync(path.join(ROOT, "supabase/functions/_shared/push_i18n.ts"),
`// GENERATED by tools/i18n/build.js from i18n/src/*.tsv — do not edit.
// Copy for server-sent pushes, keyed by app language then English text.
const PUSH: Record<string, Record<string, string>> = ${JSON.stringify(push, null, 1)};

export function pushText(locale: string, key: string, params?: Record<string, unknown>): string {
  let s = PUSH[locale]?.[key] ?? key;
  if (params) s = s.replace(/\\{\\{(\\w+)\\}\\}/g, (m, k) => (params[k] == null ? "" : String(params[k])));
  return s;
}
`);

// 3. Swift extension tables, one per file, holding only that file's keys.
const BEGIN = "// BEGIN GENERATED L10N (tools/i18n/build.js) — do not edit by hand";
const END = "// END GENERATED L10N";
const swiftStr = (s) => '"' + s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n") + '"';
const nativeKeys = read(path.join(I18N, "native-keys.json"));
const swiftFiles = {
  "ios/DriftShield/ShieldConfigurationExtension.swift": "ios/DriftShield",
  "ios/DriftMonitor/DriftMonitor.swift": "ios/DriftMonitor",
  "ios/DriftWidgets/DriftWidgets.swift": "ios/DriftWidgets",
};
for (const [file, tag] of Object.entries(swiftFiles)) {
  const fileKeys = Object.keys(nativeKeys).filter((k) => nativeKeys[k][0] === tag);
  const rows = [];
  for (const code of LANGS) {
    const entries = fileKeys.filter((k) => catalogs[code][k]).map((k) => `    ${swiftStr(k)}: ${swiftStr(catalogs[code][k])},`);
    if (entries.length) rows.push(`  ${swiftStr(code)}: [\n${entries.join("\n")}\n  ],`);
  }
  const block = `${BEGIN}
// Extensions can't see the app's JS catalogs, so each carries its own table.
// Language: what the app last wrote to the App Group (ScreenTimeModule
// .setLanguage), else the device's preferred language, else English.
fileprivate let DRIFT_L10N: [String: [String: String]] = [
${rows.join("\n") || "  :"}
]

fileprivate func driftLanguage() -> String {
  if let code = UserDefaults(suiteName: "group.com.sanghani.drift.shared")?.string(forKey: "drift_language"),
     !code.isEmpty { return code }
  let pref = Locale.preferredLanguages.first ?? "en"
  if pref.hasPrefix("zh") { return (pref.contains("Hant") || pref.contains("TW") || pref.contains("HK")) ? "zh-Hant" : "zh-Hans" }
  return String(pref.split(separator: "-").first ?? "en")
}

fileprivate func driftL(_ key: String, _ params: [String: String] = [:]) -> String {
  var s = DRIFT_L10N[driftLanguage()]?[key] ?? key
  for (k, v) in params { s = s.replacingOccurrences(of: "{{\\(k)}}", with: v) }
  return s
}
${END}
`;
  const abs = path.join(ROOT, file);
  let src = fs.readFileSync(abs, "utf8");
  const a = src.indexOf(BEGIN), b = src.indexOf(END);
  if (a >= 0 && b > a) src = src.slice(0, a) + block.trimEnd() + src.slice(b + END.length);
  else src = src.trimEnd() + "\n\n" + block;
  fs.writeFileSync(abs, src);
}

// 4. InfoPlist.strings
const plistKeys = read(path.join(I18N, "plist-keys.json")); // english -> [NSKey…]
const strEsc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");
for (const code of LANGS) {
  const lines = [];
  for (const [en, nsKeys] of Object.entries(plistKeys)) {
    const v = catalogs[code][en];
    if (v) for (const k of nsKeys) lines.push(`"${k}" = "${strEsc(v)}";`);
  }
  const dir = path.join(ROOT, "ios/Drift", `${code}.lproj`);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "InfoPlist.strings"), `/* GENERATED by tools/i18n/build.js — do not edit. */\n${lines.join("\n")}\n`);
}
console.log(problems ? `${problems} translations dropped (see warnings)` : "all translations valid");
